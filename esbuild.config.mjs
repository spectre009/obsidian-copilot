import esbuild from "esbuild";
import { realpathSync } from "fs";
import process from "process";
import { createRequire } from "module";
import { fileURLToPath } from "url";
import wasmPlugin from "./wasmPlugin.mjs";
import nodeModuleShim, { nodeBuiltinExternals } from "./nodeModuleShim.mjs";
import svgrPlugin from "./svgrPlugin.mjs";

const patchRendererUnsafeUnref = createRequire(import.meta.url)(
  "./scripts/patchRendererUnsafeUnref.js"
);
const { createBundleSizeGuard } = createRequire(import.meta.url)("./scripts/bundleSizeGuard.js");
const { COPILOT_SDK_EXTERNALS, copilotSdkNodeResolution } = createRequire(import.meta.url)(
  "./scripts/copilotSdkNodeResolution.js"
);

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/

// Polyfill for import.meta in CommonJS context
if (typeof import_meta === 'undefined') {
  var import_meta = {
    url: typeof __filename !== 'undefined' ? 'file://' + __filename : 'file:///obsidian-plugin'
  };
}

// Minimal \`process\` shim so the bundle survives MODULE EVALUATION on Obsidian
// mobile, whose WebView has no Node \`process\` global. Desktop-only code (Agent
// Mode) is statically imported and therefore evaluated on every platform; many
// of those modules — and bundled Node deps — read \`process.platform\`/\`.env\` at
// module scope, which throws "Can't find variable: process" on mobile and kills
// the whole plugin at load. On desktop (Electron) \`globalThis.process\` exists
// and is used as-is, so this only stubs mobile, where those code paths never run.
var process = globalThis.process || {
  env: {},
  platform: '',
  arch: '',
  argv: [],
  version: '',
  versions: {},
  cwd: function () { return '/'; },
  nextTick: function (cb) { Promise.resolve().then(cb); },
  on: function () {},
  off: function () {},
  once: function () {},
  emit: function () { return false; },
};
`;

/**
 * Builds the plugin's esbuild options. Exported so bundle tests resolve and evaluate modules
 * exactly as the shipped `main.js` does.
 * https://github.com/spectre009/obsidian-copilot/issues/3
 * @param production minified build with the bundle-size guard enforced, rather than a watch build
 */
export function createBuildOptions({ production }) {
  return {
    banner: {
      js: banner,
    },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
      "obsidian",
      "electron",
      "@codemirror/autocomplete",
      "@codemirror/collab",
      "@codemirror/commands",
      "@codemirror/language",
      "@codemirror/lint",
      "@codemirror/search",
      "@codemirror/state",
      "@codemirror/view",
      "@lezer/common",
      "@lezer/highlight",
      "@lezer/lr",
      ...nodeBuiltinExternals,
      ...COPILOT_SDK_EXTERNALS,
    ],
    format: "cjs",
    target: "es2020",
    charset: "utf8",
    legalComments: "eof",
    logLevel: "info",
    sourcemap: production ? false : "inline",
    treeShaking: true,
    outfile: "main.js",
    loader: { ".md": "text" },
    plugins: [
      nodeModuleShim,
      copilotSdkNodeResolution,
      svgrPlugin,
      wasmPlugin,
      patchRendererUnsafeUnref,
      createBundleSizeGuard({ production }),
    ],
    define: {
      global: "window",
      "process.env.NODE_ENV": production ? '"production"' : '"development"',
      "import.meta.url": "import_meta.url",
    },
    minify: production,
  };
}

const isEntryScript =
  !!process.argv[1] &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));

if (isEntryScript) {
  const prod = process.argv[2] === "production";
  const context = await esbuild.context(createBuildOptions({ production: prod }));

  if (prod) {
    await context.rebuild();
    process.exit(0);
  } else {
    await context.watch();
  }
}
